\set ON_ERROR_STOP on

-- Run with psql connected to the PostgreSQL administrative database.
SELECT format('CREATE DATABASE %I', 'enterprise_crm')
WHERE NOT EXISTS (
    SELECT 1
    FROM pg_database
    WHERE datname = 'enterprise_crm'
)
\gexec

\connect enterprise_crm

CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    company VARCHAR(180) NOT NULL,
    industry VARCHAR(80) NOT NULL
        CHECK (industry IN ('Technology', 'Healthcare', 'Finance', 'Manufacturing', 'Retail', 'Professional Services')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (email LIKE '%@%.%')
);

CREATE TABLE IF NOT EXISTS leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    lead_source VARCHAR(40) NOT NULL
        CHECK (lead_source IN ('website', 'referral', 'trade_show', 'partner', 'outbound')),
    status VARCHAR(24) NOT NULL
        CHECK (status IN ('new', 'qualified', 'nurturing', 'converted', 'disqualified')),
    assigned_to VARCHAR(120) NOT NULL,
    estimated_value NUMERIC(12, 2) NOT NULL CHECK (estimated_value >= 0),
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    opportunity_name VARCHAR(180) NOT NULL,
    stage VARCHAR(24) NOT NULL
        CHECK (stage IN ('qualification', 'discovery', 'proposal', 'negotiation', 'closed_won', 'closed_lost')),
    amount NUMERIC(14, 2) NOT NULL CHECK (amount >= 0),
    expected_close_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CHECK (expected_close_date >= created_at::DATE)
);

CREATE TABLE IF NOT EXISTS activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    activity_type VARCHAR(24) NOT NULL
        CHECK (activity_type IN ('call', 'email', 'meeting', 'demo', 'task')),
    description VARCHAR(500) NOT NULL,
    activity_date TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_customers_industry_created_at
    ON customers (industry, created_at);
CREATE INDEX IF NOT EXISTS idx_leads_customer_created_at
    ON leads (customer_id, created_at);
CREATE INDEX IF NOT EXISTS idx_leads_status_created_at
    ON leads (status, created_at);
CREATE INDEX IF NOT EXISTS idx_opportunities_customer_stage
    ON opportunities (customer_id, stage);
CREATE INDEX IF NOT EXISTS idx_opportunities_close_date_stage
    ON opportunities (expected_close_date, stage);
CREATE INDEX IF NOT EXISTS idx_activities_customer_date
    ON activities (customer_id, activity_date);
CREATE INDEX IF NOT EXISTS idx_activities_type_date
    ON activities (activity_type, activity_date);
